#!/usr/bin/env python3
"""a4k-cnn.py <Anime4K_Upscale_CNN_x2_S.glsl> > bridge/shell/sharpen_a4k_cnn.h: the four convolution layers of Anime4K v3.2 "Upscale CNN x2 (S)" (bloc97,
MIT, github.com/bloc97/Anime4K, glsl/Upscale/Anime4K_Upscale_CNN_x2_S.glsl) as GLES2 fragment shaders (FS_A4K_C1..C4). The weights are copied verbatim; only the
mpv hook plumbing changes: one texel fetch per tap (positions are texel centres, `src` = the source size), layers 2-4 read the previous layer as relu(x) and relu(-x)."""
import re, sys

src = open(sys.argv[1]).read()
HEAD = 'precision highp float;\\nuniform vec2 src; varying vec2 uv;\\n'
EXT = '#extension GL_OES_EGL_image_external : require\\n'
out = ['/* Generated by tools/gen/a4k-cnn.py from Anime4K_Upscale_CNN_x2_S.glsl (bloc97/Anime4K, MIT): the CNN\'s four layers as GLES2 fragment shaders. Do not edit. */']
for n, blk in enumerate(src.split('//!DESC')[1:5]):
    sampler = ['tex', 'g', 'n', 'dir'][n]
    taps = re.findall(r'result \+?= mat4\(([^)]*)\) \* go_(\d)\((-?\d\.0), (-?\d\.0)\)', blk)
    bias = re.search(r'result \+= vec4\(([^)]*)\);', blk).group(1)
    L = []
    decl = ('uniform samplerExternalOES tex;' if n == 0 else 'uniform sampler2D %s;' % sampler)
    L.append('"%s%s%s\\n"' % (EXT if n == 0 else '', HEAD, decl))
    L.append('"vec4 F(vec2 p, float x, float y) { return texture2D(%s, (p + vec2(x, y) + 0.5) / src); }\\n"' % sampler)
    L.append('"void main() {\\n  vec2 p = floor(uv * src);\\n  vec4 r = vec4(%s), a;\\n"' % bias)
    if n == 0:
        for m, g, x, y in taps:
            L.append('"  r += mat4(%s) * F(p, %s, %s);\\n"' % (m.replace(' ', ''), x, y))
    else:
        by = {}
        for m, g, x, y in taps: by.setdefault((x, y), {})[g] = m.replace(' ', '')
        for (x, y), d in by.items():
            L.append('"  a = F(p, %s, %s); r += mat4(%s) * max(a, 0.0) + mat4(%s) * max(-a, 0.0);\\n"' % (x, y, d['0'], d['1']))
    L.append('"  gl_FragColor = r;\\n}\\n"')
    out.append('static const char *FS_A4K_C%d =\n    %s;' % (n + 1, '\n    '.join(L)))
print('\n'.join(out))
