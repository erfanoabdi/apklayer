#!/usr/bin/env python3
"""sharpen-spv.py <glslangValidator> [out.h]: bridge/shell/sharpen_vk_spv.h, the render filter's shaders as SPIR-V for the Vulkan backend (sharpen_vk.c).
The single source of the filters is the GLES2 fragment shaders in bridge/shell/sharpen.c, sharpen_more.h (C string literals); each is converted
mechanically (sampler/uniform declarations, texture2D, gl_FragColor, NIS's coefficient banks from sharpen_nis.h as constant arrays) and compiled with glslang.
Samplers are bindings 0..3 (tex, g, n, dir); every other uniform is the one push-constant block below. Run after changing a filter shader and commit the header."""
import re, subprocess, sys, tempfile, os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SH = ROOT / 'bridge/shell'
SAMPLERS = {'tex': 0, 'g': 1, 'n': 2, 'dir': 3}
ORDER = ['FS_UP', 'FS_CAS', 'FS_NIS', 'FS_SGSR', 'FS_LANCZOS', 'FS_A4K_PRE', 'FS_A4K_Y', 'FS_A4K_X', 'FS_A4K_DIR', 'FS_A4K_APPLY', 'FS_DOWN']
VS = """#version 450
layout(location = 0) out vec2 uv;
void main() { vec2 p = vec2(float((gl_VertexIndex << 1) & 2), float(gl_VertexIndex & 2)) * 2.0 - 1.0; uv = p * 0.5 + 0.5; gl_Position = vec4(p, 0.0, 1.0); }
"""
HEAD = """#version 450
layout(push_constant) uniform PC { vec2 src; vec2 scl; vec2 px; vec2 d; float sharp; float down; };
layout(location = 0) in vec2 uv;
layout(location = 0) out vec4 fc;
"""


def unescape(lit):
    return lit.encode().decode('unicode_escape')


def literals(body, macros):
    out = ''
    for m in re.finditer(r'/\*.*?\*/|//[^\n]*|"((?:[^"\\]|\\.)*)"|([A-Z0-9_]+)', body, re.S):  # C comments between the literals are skipped
        if m.group(1) is not None: out += unescape(m.group(1))
        elif m.group(2) is not None: out += macros[m.group(2)]
    return out


def sources():
    text = ''.join((SH / f).read_text() for f in ('sharpen.c', 'sharpen_more.h', 'sharpen_down.h'))
    macros = {m.group(1): unescape(m.group(2)) for m in re.finditer(r'#define (\w+) "((?:[^"\\]|\\.)*)"\s*\n', text)}
    macros['A4K_HEAD'] = macros.get('A4K_HEAD', '')
    res = {}
    for m in re.finditer(r'static const char \*(FS_\w+) =\s*(.*?);\n', text, re.S):
        if m.group(1) in ORDER: res[m.group(1)] = literals(m.group(2), macros)
    return res


def nis_arrays():
    t = (SH / 'sharpen_nis.h').read_text()
    out = ''
    for name, glname in (('nis_coef_scale', 'cs'), ('nis_coef_usm', 'cu')):
        body = re.search(name + r'\[512\] = \{(.*?)\};', t, re.S).group(1)
        v = [x.strip().rstrip('f') for x in body.replace('\n', ' ').split(',') if x.strip()]
        out += 'const vec4 %s[128] = vec4[128](%s);\n' % (glname, ','.join('vec4(%s,%s,%s,%s)' % tuple(v[i:i + 4]) for i in range(0, 512, 4)))
    return out


def convert(name, s):
    s = s.replace('#extension GL_OES_EGL_image_external : require\n', '').replace('precision highp float;\n', '')
    decl = ''
    for m in re.finditer(r'uniform (?:samplerExternalOES|sampler2D) (\w+);', s):
        decl += 'layout(set = 0, binding = %d) uniform sampler2D %s;\n' % (SAMPLERS[m.group(1)], m.group(1))
    s = re.sub(r'uniform (?:samplerExternalOES|sampler2D) \w+;', '', s)
    if 'uniform vec4 cs[128]' in s:
        s = s.replace('uniform vec4 cs[128];', '').replace('uniform vec4 cu[128];', '')
        decl += nis_arrays()
    s = re.sub(r'uniform (?:vec2|float) \w+;', '', s)
    s = s.replace('varying vec2 uv;', '')
    s = s.replace('gl_FragColor', 'fc').replace('texture2D(', 'texture(')
    assert 'uniform' not in s and 'varying' not in s, name
    return HEAD + decl + s


def compile_(glslang, stage, text, tmp, name):
    f = os.path.join(tmp, name + '.' + stage)
    Path(f).write_text(text)
    o = f + '.spv'
    r = subprocess.run([glslang, '-V', '-S', stage, f, '-o', o], capture_output=True, text=True)
    if r.returncode: sys.exit('%s: glslang failed:\n%s%s\n%s' % (name, r.stdout, r.stderr, text[:400]))
    return Path(o).read_bytes()


def array(name, data):
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    lines = ['static const uint32_t %s[%d] = {' % (name, len(words))]
    for i in range(0, len(words), 8): lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
    return '\n'.join(lines) + '\n};\n'


def main():
    glslang = sys.argv[1]
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else SH / 'sharpen_vk_spv.h'
    src = sources()
    assert sorted(src) == sorted(ORDER), sorted(set(ORDER) - set(src))
    h = '/* Generated by tools/gen/sharpen-spv.py from the GLES shaders (do not edit): the render filter\'s SPIR-V for sharpen_vk.c. */\n'
    with tempfile.TemporaryDirectory(prefix='sharpen-spv-') as tmp:
        h += array('svk_spv_vs', compile_(glslang, 'vert', VS, tmp, 'vs'))
        for n in ORDER:
            h += array('svk_spv_' + n[3:].lower(), compile_(glslang, 'frag', convert(n, src[n]), tmp, n))
    h += 'static const struct { const uint32_t *code; unsigned size; } svk_spv[] = {\n' + ''.join('    { svk_spv_%s, sizeof svk_spv_%s },\n' % (n[3:].lower(), n[3:].lower()) for n in ORDER) + '};\n'
    out.write_text(h)
    print('%s: %d shaders, %d bytes' % (out, len(ORDER), len(h)))


main()
