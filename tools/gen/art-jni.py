#!/usr/bin/env python3
"""Writes bridge/native/art_jni_names.inc: one X(index, "<ART's mangled name>") per entry of the JNI function table and of the JavaVM invoke
table, in table order, from a JDK's jni.h (usage: art-jni.py <jni.h> > bridge/native/art_jni_names.inc). ART 13/14 (art/runtime/jni/jni_internal.cc,
java_vm_ext.cc): art::JNI<false>::Name and art::JII::Name; its table ends at GetObjectRefType (229 functions, a newer JDK has more)."""
import re
import sys

text = re.sub(r'\s+', ' ', re.sub(r'/\*.*?\*/', '', open(sys.argv[1]).read(), flags=re.S))
body = re.search(r'struct JNINativeInterface_ \{(.*?)\};', text).group(1)
funcs = re.findall(r'\(JNICALL \*(\w+)\) ?\(([^)]*)\)', body)[:229]
named = {'JNIEnv': 'P7_JNIEnv', 'jobject': 'P8_jobject', 'jclass': 'P7_jclass', 'jstring': 'P8_jstring', 'jmethodID': 'P10_jmethodID', 'jfieldID': 'P9_jfieldID',
         'jthrowable': 'P11_jthrowable', 'jarray': 'P8_jarray', 'jweak': 'P8_jobject', 'jvalue': 'PK6jvalue', 'JNINativeMethod': 'PK15JNINativeMethod',
         'jobjectRefType': '15jobjectRefType'}
scalar = {'jint': 'i', 'jsize': 'i', 'jlong': 'l', 'jboolean': 'h', 'jbyte': 'a', 'jchar': 't', 'jshort': 's', 'jfloat': 'f', 'jdouble': 'd', 'void': 'v'}
for t in ('boolean', 'byte', 'char', 'short', 'int', 'long', 'float', 'double', 'object'):
    named['j%sArray' % t] = 'P%d_j%sArray' % (len(t) + 7, t)


def mangle(param):
    param = param.strip()
    if param == '...': return 'z'
    if param.startswith('va_list'): return '\x01'  # va_list: C picks the target's spelling (VA)
    const = param.startswith('const ')
    words = re.sub(r'^const ', '', param).replace('*', ' * ').split()
    stars = words.count('*')
    base = [w for w in words if w != '*'][0]
    if not stars:  # a type with a parameter name, or a bare type (void)
        return scalar.get(base) or named[base]
    if base == 'void': return 'P' * stars + 'v'
    if base == 'char': return 'P' * (stars - 1) + 'P' + ('K' if const else '') + 'c'
    if base == 'JavaVM': return 'P' * stars + '7_JavaVM'
    if base in scalar: return 'P' * stars + ('K' if const else '') + scalar[base]
    inner = named[base]  # 'P7_jclass' etc.: already one pointer level
    return 'P' * (stars - 1) + inner


sys.stdout.write('/* generated by tools/gen/art-jni.py from a jni.h: X(table index, the symbol ART names it, argument position of a jmethodID or 9) */\n')
for i, (func, params) in enumerate(funcs):
    plist = [p for p in params.split(',')]
    plist = [re.sub(r'\b(\w+)$', '', p.strip()) if ' ' in p.strip() and not p.strip().endswith('*') and p.strip() != '...' and not re.fullmatch(r'(const )?\w+', p.strip()) else p for p in plist]
    sym = '_ZN3art3JNIILb0EE%d%sE%s' % (len(func), func, ''.join(mangle(p) for p in plist))
    ids = [n for n, p in enumerate(plist) if p.strip().startswith('jmethodID')]  # 3rd argument: the register holding a jmethodID (9: none), translated by libart_jni.c
    sys.stdout.write('X(%d, "%s", %d)\n' % (i + 4, sym.replace('\x01', '" VA "'), ids[0] if ids else 9))
for i, (func, params) in enumerate([('DestroyJavaVM', 'JavaVM*'), ('AttachCurrentThread', 'JavaVM*, void**, void*'), ('DetachCurrentThread', 'JavaVM*'),
                                    ('GetEnv', 'JavaVM*, void**, jint'), ('AttachCurrentThreadAsDaemon', 'JavaVM*, void**, void*')]):
    sys.stdout.write('Y(%d, "_ZN3art3JII%d%sE%s")\n' % (i + 3, len(func), func, ''.join(mangle(p) for p in params.split(','))))
