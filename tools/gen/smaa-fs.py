#!/usr/bin/env python3
"""smaa-fs.py: bridge/shell/sharpen_smaa_fs.h from tools/gen/smaa/ (the .glsl files) (the SMAA 1x passes as GLSL ES 1.00, a port of iryoku/smaa SMAA.hlsl, MIT).
The .glsl files are the source; run after editing one and commit the header."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'tools/gen/smaa'
out = ['/* GENERATED by tools/gen/smaa-fs.py from tools/gen/smaa/ (the .glsl files): the SMAA 1x passes (GLSL ES 1.00), a port of iryoku/smaa SMAA.hlsl (MIT, docs/THIRD_PARTY.md).\n'
       ' * The HLSL texture-space algorithm unchanged; level-zero fetches are texture2D (no mip maps), the search loops have constant bounds, `discard` is a zero edge.\n'
       ' * sharpen_smaa.c puts the preset macros (SMAA_MAX_SEARCH_STEPS, SMAA_MAX_SEARCH_STEPS_DIAG, SMAA_CORNER_ROUNDING)\n'
       ' * and SRC_EXT (the source is the app\'s external image) before each. */\n']
for name, f in (('SMAA_FS_EDGE_COLOR', 'edge_color'), ('SMAA_FS_WEIGHTS', 'weights'), ('SMAA_FS_BLEND', 'blend')):
    out.append('static const char *%s =\n' % name)
    lines = (SRC / (f + '.glsl')).read_text().rstrip('\n').split('\n')
    for i, l in enumerate(lines):
        out.append('    "%s\\n"%s\n' % (l.replace('\\', '\\\\').replace('"', '\\"'), ';' if i == len(lines) - 1 else ''))
(ROOT / 'bridge/shell/sharpen_smaa_fs.h').write_text(''.join(out))

# the CMAA2 compute shader (one source, four kernels chosen by K_EDGES / K_ARGS / K_CAND / K_APPLY)
cm = ['/* GENERATED by tools/gen/smaa-fs.py from tools/gen/cmaa/cmaa.comp: Intel CMAA2 (MIT, GameTechDev/CMAA2 CMAA2.hlsl) as GLSL ES 3.10 compute, single sample, luma edge path,\n'
      ' * gamma encoded input (docs/THIRD_PARTY.md). sharpen_cmaa.c puts "#version 310 es", CM_EDGE_THRESHOLD, CM_EXTRA_SHARPNESS and one K_ kernel macro first. */\n',
      'static const char *CMAA_CS =\n']
lines = (ROOT / 'tools/gen/cmaa/cmaa.comp').read_text().rstrip('\n').split('\n')
for i, l in enumerate(lines):
    cm.append('    "%s\\n"%s\n' % (l.replace('\\', '\\\\').replace('"', '\\"'), ';' if i == len(lines) - 1 else ''))
(ROOT / 'bridge/shell/sharpen_cmaa_cs.h').write_text(''.join(cm))
