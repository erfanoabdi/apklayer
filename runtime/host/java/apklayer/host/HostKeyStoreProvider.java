package apklayer.host;

import android.security.keystore.KeyGenParameterSpec;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.Key;
import java.security.KeyStore;
import java.security.KeyStoreException;
import java.security.KeyStoreSpi;
import java.security.NoSuchAlgorithmException;
import java.security.Provider;
import java.security.SecureRandom;
import java.security.UnrecoverableKeyException;
import java.security.cert.Certificate;
import java.security.cert.CertificateException;
import java.security.spec.AlgorithmParameterSpec;
import java.util.Collections;
import java.util.Date;
import java.util.Enumeration;
import javax.crypto.KeyGenerator;
import javax.crypto.KeyGeneratorSpi;
import javax.crypto.SecretKey;

/**
 * "AndroidKeyStore" for the sandbox (PLAN P5.5): Robolectric has none, and apps fail the moment they ask for it
 * (EncryptedSharedPreferences, MasterKey, ...). A software store: secret keys live in a JCEKS file in the app's
 * data directory. Android's hardware-backed non-exportability is not reproduced. Key pairs (RSA, EC) with a self-signed certificate are generated by the JDK.
 */
public final class HostKeyStoreProvider extends Provider {
    private static final char[] PASSWORD = "apklayer".toCharArray();

    public HostKeyStoreProvider() {
        super("AndroidKeyStore", "1.0", "apklayer software keystore");
        put("KeyStore.AndroidKeyStore", Store.class.getName());
        put("KeyGenerator.AES", AesGenerator.class.getName());
        put("KeyGenerator.HmacSHA256", HmacGenerator.class.getName());
        put("KeyPairGenerator.RSA", RsaPairGenerator.class.getName());
        put("KeyPairGenerator.EC", EcPairGenerator.class.getName());
    }

    private static Path file() {
        return Path.of(System.getProperty("apklayer.data", System.getProperty("java.io.tmpdir")), "keystore.jceks");
    }

    private static synchronized KeyStore shared() throws KeyStoreException {
        if (shared == null) {
            try {
                shared = KeyStore.getInstance("JCEKS");
                if (Files.exists(file())) try (InputStream in = Files.newInputStream(file())) { shared.load(in, PASSWORD); }
                else shared.load(null, PASSWORD);
            } catch (IOException | NoSuchAlgorithmException | CertificateException e) {
                throw new KeyStoreException(e);
            }
        }
        return shared;
    }

    private static KeyStore shared;

    private static synchronized void persist() throws KeyStoreException {
        try (OutputStream out = Files.newOutputStream(file())) {
            shared().store(out, PASSWORD);
        } catch (IOException | NoSuchAlgorithmException | CertificateException e) {
            throw new KeyStoreException(e);
        }
    }

    /** KeyStore.getInstance("AndroidKeyStore"): every call sees the same app-wide store. */
    public static final class Store extends KeyStoreSpi {
        @Override public Key engineGetKey(String alias, char[] p) throws NoSuchAlgorithmException, UnrecoverableKeyException {
            try { return shared().getKey(alias, PASSWORD); } catch (KeyStoreException e) { throw new UnrecoverableKeyException(e.toString()); }
        }
        @Override public Certificate[] engineGetCertificateChain(String alias) {
            try { return shared().getCertificateChain(alias); } catch (KeyStoreException e) { return null; }
        }
        @Override public Certificate engineGetCertificate(String alias) {
            try { return shared().getCertificate(alias); } catch (KeyStoreException e) { return null; }
        }
        @Override public Date engineGetCreationDate(String alias) {
            try { return shared().getCreationDate(alias); } catch (KeyStoreException e) { return null; }
        }
        @Override public void engineSetKeyEntry(String alias, Key key, char[] p, Certificate[] chain) throws KeyStoreException {
            shared().setKeyEntry(alias, key, PASSWORD, chain);
            persist();
        }
        @Override public void engineSetKeyEntry(String alias, byte[] key, Certificate[] chain) throws KeyStoreException {
            throw new KeyStoreException("encoded keys are not supported");
        }
        @Override public void engineSetCertificateEntry(String alias, Certificate cert) throws KeyStoreException {
            shared().setCertificateEntry(alias, cert);
            persist();
        }
        @Override public void engineDeleteEntry(String alias) throws KeyStoreException {
            shared().deleteEntry(alias);
            persist();
        }
        @Override public Enumeration<String> engineAliases() {
            try { return shared().aliases(); } catch (KeyStoreException e) { return Collections.emptyEnumeration(); }
        }
        @Override public boolean engineContainsAlias(String alias) {
            try { return shared().containsAlias(alias); } catch (KeyStoreException e) { return false; }
        }
        @Override public int engineSize() {
            try { return shared().size(); } catch (KeyStoreException e) { return 0; }
        }
        @Override public boolean engineIsKeyEntry(String alias) {
            try { return shared().isKeyEntry(alias); } catch (KeyStoreException e) { return false; }
        }
        @Override public boolean engineIsCertificateEntry(String alias) {
            try { return shared().isCertificateEntry(alias); } catch (KeyStoreException e) { return false; }
        }
        @Override public String engineGetCertificateAlias(Certificate cert) {
            try { return shared().getCertificateAlias(cert); } catch (KeyStoreException e) { return null; }
        }
        @Override public void engineStore(OutputStream stream, char[] password) {}
        @Override public void engineLoad(InputStream stream, char[] password) {}
    }

    /** KeyGenerator.getInstance("AES", "AndroidKeyStore") with a KeyGenParameterSpec: generate and store under its alias. */
    public static class AesGenerator extends KeyGeneratorSpi {
        private String alias;
        private int bits = 256;
        private final String algorithm;

        public AesGenerator() { this("AES"); }

        AesGenerator(String algorithm) { this.algorithm = algorithm; }

        @Override protected void engineInit(SecureRandom random) { throw new UnsupportedOperationException("a KeyGenParameterSpec is required"); }

        @Override protected void engineInit(AlgorithmParameterSpec params, SecureRandom random) throws java.security.InvalidAlgorithmParameterException {
            if (!(params instanceof KeyGenParameterSpec spec)) throw new java.security.InvalidAlgorithmParameterException("KeyGenParameterSpec required");
            alias = spec.getKeystoreAlias();
            if (spec.getKeySize() > 0) bits = spec.getKeySize();
        }

        @Override protected void engineInit(int keysize, SecureRandom random) { bits = keysize; }

        @Override protected SecretKey engineGenerateKey() {
            try {
                // the JDK's own generator
                KeyGenerator gen = KeyGenerator.getInstance(algorithm, "SunJCE");
                gen.init(bits);
                SecretKey key = gen.generateKey();
                if (alias != null) {
                    shared().setKeyEntry(alias, key, PASSWORD, null);
                    persist();
                }
                return key;
                } catch (NoSuchAlgorithmException | KeyStoreException | java.security.NoSuchProviderException e) {
                throw new IllegalStateException(e);
            }
        }
    }

    public static final class HmacGenerator extends AesGenerator {
        public HmacGenerator() { super("HmacSHA256"); }
    }

    /**
     * KeyPairGenerator.getInstance("RSA" | "EC", "AndroidKeyStore") with a KeyGenParameterSpec: the JDK generates the pair, a self-signed certificate (subject,
     * serial and validity from the spec, as the platform's keystore makes one without attestation) goes with the private key under the alias.
     */
    public abstract static class PairGenerator extends java.security.KeyPairGeneratorSpi {
        private final String algorithm;
        private KeyGenParameterSpec spec;
        private int bits;

        PairGenerator(String algorithm, int defaultBits) { this.algorithm = algorithm; this.bits = defaultBits; }

        @Override public void initialize(int keysize, SecureRandom random) { bits = keysize; }

        @Override public void initialize(AlgorithmParameterSpec params, SecureRandom random) throws java.security.InvalidAlgorithmParameterException {
            if (!(params instanceof KeyGenParameterSpec s)) throw new java.security.InvalidAlgorithmParameterException("KeyGenParameterSpec required");
            spec = s;
            if (s.getKeySize() > 0) bits = s.getKeySize();
            else if (s.getAlgorithmParameterSpec() instanceof java.security.spec.ECGenParameterSpec ec) bits = ec.getName().contains("384") ? 384 : ec.getName().contains("521") ? 521 : 256;
        }

        @Override public java.security.KeyPair generateKeyPair() {
            if (spec == null) throw new IllegalStateException("not initialized with a KeyGenParameterSpec");
            try {
                String signature = "RSA".equals(algorithm) ? "SHA256withRSA" : "SHA256withECDSA";
                sun.security.tools.keytool.CertAndKeyGen generator = new sun.security.tools.keytool.CertAndKeyGen(algorithm, signature);
                generator.generate(bits);
                Date from = spec.getKeyValidityStart() != null ? spec.getKeyValidityStart() : new Date();
                Date to = spec.getCertificateNotAfter() != null ? spec.getCertificateNotAfter() : new Date(from.getTime() + 25L * 365 * 24 * 3600 * 1000);
                String subject = spec.getCertificateSubject() != null ? spec.getCertificateSubject().getName() : "CN=Android Keystore Key";
                java.security.cert.X509Certificate certificate = generator.getSelfCertificate(new sun.security.x509.X500Name(subject), from, (to.getTime() - from.getTime()) / 1000);
                java.security.PrivateKey privateKey = generator.getPrivateKey();
                shared().setKeyEntry(spec.getKeystoreAlias(), privateKey, PASSWORD, new Certificate[] {certificate});
                persist();
                return new java.security.KeyPair(generator.getPublicKey(), privateKey);
            } catch (Exception e) {
                throw new IllegalStateException(e);
            }
        }
    }

    public static final class RsaPairGenerator extends PairGenerator { public RsaPairGenerator() { super("RSA", 2048); } }

    public static final class EcPairGenerator extends PairGenerator { public EcPairGenerator() { super("EC", 256); } }
}
