#!/usr/bin/env python3
"""Generates runtime/host/java/apklayer/loader/ApklayerUnsafe.java from the routed-method table of the vendored dex2jvm
(UnsafeRepoint.java). Usage: scripts/gen-unsafe-redirect.py > runtime/host/java/apklayer/loader/ApklayerUnsafe.java"""
import re, sys

TYPES = {'Z': 'boolean', 'B': 'byte', 'C': 'char', 'S': 'short', 'I': 'int', 'J': 'long', 'F': 'float', 'D': 'double', 'V': 'void',
         'Ljava/lang/Object;': 'Object'}
src = open('runtime/dex2jvm/io/github/kksimp/dex2jvm/UnsafeRepoint.java').read()
table = sorted(set(re.findall(r'"(\w+\([^"]*\)\S+)"', src)))

def split(desc):
    params, ret = re.match(r'\((.*)\)(.*)', desc).groups()
    return re.findall(r'L[^;]+;|[ZBCSIJFD]', params), ret

print('''package apklayer.loader;

import sun.misc.Unsafe;

/**
 * Target of the converter's sun.misc.Unsafe redirect (dex2jvm Options.unsafeRedirect, set in HostDefaults). Generated by
 * scripts/gen-unsafe-redirect.py from the converter's routed-method table; do not edit by hand.
 *
 * Every routed memory accessor of an app's Unsafe calls arrives here with the receiver as first parameter. Offsets and addresses
 * that apps (hidden-API bypass libraries such as HiddenApiBypass) derive from ART's object layout mean nothing on HotSpot:
 *  - a base object whose layout belongs to the VM (Class, reflection objects, method handles) is answered empty: reads return
 *    0/null/false, writes are dropped, compare-and-swap reports false. The library finds no methods and falls back to plain reflection.
 *  - an access HotSpot refuses with InternalError is rethrown as the ReflectiveOperationException such libraries catch, so they fall
 *    back instead of aborting the app's startup.
 * Everything else, including every accessor on an ordinary app object (protobuf, Gson, atomic field updaters), goes straight to the
 * real Unsafe. The first few empty answers are logged.
 */
public final class ApklayerUnsafe {
    private ApklayerUnsafe() {}

    @SuppressWarnings("unchecked")
    private static <T extends Throwable> RuntimeException sneaky(Throwable t) throws T { throw (T) t; }

    private static final java.util.concurrent.atomic.AtomicInteger hits = new java.util.concurrent.atomic.AtomicInteger();

    private static boolean vmOwned(Object o, String what) {
        boolean owned = o instanceof Class || o instanceof java.lang.reflect.AccessibleObject || o instanceof java.lang.invoke.MethodHandle
                || o instanceof java.lang.invoke.MethodHandleInfo || o instanceof java.lang.invoke.MethodType;
        if (owned && hits.incrementAndGet() <= 8)
            System.err.println("[apklayer] Unsafe." + what + " inside a " + o.getClass().getName() + " answered empty: ART object layout walk on HotSpot");
        return owned;
    }

    private static RuntimeException fault(InternalError e) {
        ReflectiveOperationException wrapped = new ReflectiveOperationException("unsafe access outside the JVM's memory", e);
        return ApklayerUnsafe.<RuntimeException>sneaky(wrapped);
    }
''')
for entry in table:
    name, desc = re.match(r'(\w+)(\(.*)', entry).groups()
    params, ret = split(desc)
    decl = ['Unsafe u'] + ['%s a%d' % (TYPES[p], i) for i, p in enumerate(params)]
    call = 'u.%s(%s)' % (name, ', '.join('a%d' % i for i in range(len(params))))
    ret_j = TYPES[ret]
    ret_stmt = call + ';' if ret_j == 'void' else 'return ' + call + ';'
    zero = {'void': '', 'boolean': 'false', 'Object': 'null'}.get(ret_j, '0')
    empty = 'return;' if ret_j == 'void' else 'return %s;' % zero
    guard = '        if (vmOwned(a0, "%s")) %s\n' % (name, empty) if params and params[0] == 'Ljava/lang/Object;' else ''
    print('    public static %s %s(%s) {\n%s        try { %s } catch (InternalError e) { throw fault(e); }\n    }\n' % (ret_j, name, ', '.join(decl), guard, ret_stmt))
print('}')
