#!/usr/bin/env python3
"""gen-tree-files-lock: lists every file the arm64 route takes from the LineageOS build (~/los24 in OrbStack) and stages on the VM,
with sha256, size and where it came from, into deps/android-tree-files.lock (committed), so nothing is forgotten or unreproducible.
Run on the Mac:  scripts/gen-tree-files-lock.py   (reads the VM over ssh, resolves origins in OrbStack, never writes to either)
Each line: <sha256> <size> <path on the VM, relative to ~> <origin in the tree> <status>
status: same (identical to the tree's file), patched (differs: see the note column), apklayer (built from vendor/apklayer), unresolved."""
import hashlib, subprocess, sys, datetime, pathlib

VM = "parallels@10.211.55.4"
SSH = ["sshpass", "-p", "1234", "ssh", "-o", "StrictHostKeyChecking=no", VM]
OUT = "out/target/product/generic_arm64"

def sh(cmd, orb=False):
    c = ["orb", "-m", "ubuntu22-x86", "bash", "-c", cmd] if orb else SSH + [cmd]
    return subprocess.run(c, capture_output=True, text=True, check=True).stdout

print("Hashing staged Android artifacts", flush=True)
# what lives on the VM: the Android libraries, and the other tree-derived files
vm = sh("cd ~ && { find android-arm64/lib64 -type f; find arm64-native/aosp/android-all arm64-native/aosp/Robolectric_all.jar arm64-native/android-root -path arm64-native/android-root/data -prune -o -type f -print; } | xargs sha256sum | sed 's/  / /' ; "
        "find android-arm64/lib64 arm64-native/aosp/android-all arm64-native/aosp/Robolectric_all.jar arm64-native/android-root -path arm64-native/android-root/data -prune -o -type f -printf '%s %p\\n'")
sums, sizes = {}, {}
for line in vm.splitlines():
    a, b = line.split(" ", 1)
    if len(a) == 64: sums[b] = a
    else: sizes[b] = int(a)

print("Resolving build-output origins", flush=True)
# the tree's sha256 of the candidate origins, computed once in OrbStack
names = sorted({p.split("/")[-1] for p in sums if p.startswith("android-arm64/lib64/")})
orb = sh("cd ~/los24 && for n in %s; do f=%s/system/lib64/$n; [ -f $f ] && sha256sum $f; done; "
         "for n in %s; do for f in %s/apex/*/lib64/$n; do [ -f $f ] && sha256sum $f; done; done; "
         "find out/soong/.intermediates/vendor/apklayer -name '*.so' -path '*android_arm64_armv8-a_shared/*' -not -path '*unstripped*' -not -path '*before_final*' | xargs sha256sum; "
         "grep -m3 'ro.build.fingerprint=\\|ro.build.date=\\|ro.build.version.release=' %s/system/build.prop" % (" ".join(names), OUT, " ".join(names), OUT, OUT), orb=True)
tree, apk, ident = {}, {}, []
for line in orb.splitlines():
    if line.startswith("ro."): ident.append(line); continue
    h, p = line.split("  ", 1)
    d = apk if "vendor/apklayer" in p else tree
    if p.split("/")[-1] not in d or "/system/lib64/" in p: d[p.split("/")[-1]] = (h, p)  # system/lib64 wins over a same-named APEX copy

rows = []
for p in sorted(sums):
    n, h = p.split("/")[-1], sums[p]
    if p.startswith("android-arm64/lib64/"):
        if n in apk and apk[n][0] == h: origin, st = apk[n][1], "apklayer"
        elif n in tree and tree[n][0] == h: origin, st = tree[n][1], "same"
        elif n in tree: origin, st = tree[n][1], "patched"
        elif n in apk: origin, st = apk[n][1], "patched"
        else: origin, st = "-", "unresolved"
    else:
        origin, st = "(staged from the tree's build outputs, see docs/AOSP-BUILDS.md)", "same"
        if "/android-all/" in p and p.endswith(".jar"):
            origin, st = "(tree framework with apklayer JNI shim; scripts/build-native-arm64.sh)", "patched"
        prefix = "arm64-native/android-root/"
        if p.startswith(prefix):
            own = pathlib.Path(__file__).resolve().parent.parent / "bridge/native/android-root" / p[len(prefix):]
            if own.is_file() and hashlib.sha256(own.read_bytes()).hexdigest() == h:
                origin, st = str(own.relative_to(pathlib.Path(__file__).resolve().parent.parent)), "apklayer"
    rows.append((h, sizes[p], p, origin, st))

text = ["# Files the arm64 route takes from the LineageOS build (generated by scripts/gen-tree-files-lock.py; do not edit).",
        "# Tree: ~/los24 (OrbStack), product gsi_arm64 userdebug. " + "; ".join(ident),
        "# Generated: " + datetime.date.today().isoformat(), "# <sha256> <size> <path under ~ on the VM> <origin under ~/los24> <status>"]
text += ["%s %d %s %s %s" % r for r in rows]
path = pathlib.Path(__file__).resolve().parent.parent / "deps" / "android-tree-files.lock"
path.write_text("\n".join(text) + "\n")
by = {}
for r in rows: by[r[4]] = by.get(r[4], 0) + 1
print(len(rows), "files,", by, "->", path)
