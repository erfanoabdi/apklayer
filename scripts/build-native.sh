#!/bin/sh
# build-native: stage the native runtime (PLAN P7) on this machine (arm64 VM, x86_64 PC) from the tree's build outputs.
# Usage (from the repo root): scripts/build-native.sh <native-dir> <javac-shards-dir> <host-classes-dir>
#   APKLAYER_BT (bionic_translation's build dir, default ~/bt-arm/bionic_translation/b) and APKLAYER_ANDROID_LIBS (the staged Android libraries, default ~/android-arm64/lib64)
#   choose the inputs: an x86_64 machine sets them to its own (docs/X86_64.md).
#   native-dir:   has aosp/android-all/*.jar (the tree's framework jar) and receives native-runtime.jar
#   javac-shards: ~/los24/out/soong/.intermediates/frameworks/base/framework-minus-apex/android_common/javac (copied here)
#   the shim comes from bridge/native/runtime_shim.c + android_platform.c + android_stubs.c (see scripts/android-stubs.py)
set -e
native="$1" shards="$2" classes="$3" tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
bt="${APKLAYER_BT:-$HOME/bt-arm/bionic_translation/b}"
libs="${APKLAYER_ANDROID_LIBS:-$HOME/android-arm64/lib64}"
scripts/patch-bionic-translation.sh "$(dirname "$bt")"
ninja -C "$bt"  # build real versioned outputs; symlink targets do not rebuild them
JH="$(dirname "$(dirname "$(readlink -f "$(command -v java)")")")"
cc -shared -fPIC -O2 -Wall -I"$JH/include" -I"$JH/include/linux" -o "$tmp/libandroid_runtime.so" \
    bridge/native/runtime_shim.c bridge/native/media_runtime.c bridge/native/binder_runtime.c bridge/native/app_native.c bridge/native/native_loader.c bridge/native/android_platform.c bridge/native/properties.c bridge/native/paths.c bridge/native/android_stubs.c \
    -L"$bt" -ldl_bio -Wl,-rpath,"$bt"
# the launcher for Android executables built as libraries (btload --main) and the property tool, in $native/bin
mkdir -p "$native/bin" "$native/android-root"
[ -e "$native/android-libs" ] || ln -s "$libs" "$native/android-libs"
cp -r bridge/native/android-root/. "$native/android-root/"  # apklayer's own files of the Android root (VINTF manifest of our HALs); the tree's come from scripts/collect-android-root.sh
cc -O2 -Wall -o "$native/bin/btload" scripts/btload.c bridge/native/android_platform.c bridge/native/properties.c bridge/native/paths.c bridge/native/binder_compat.c bridge/native/android_stubs.c \
    -rdynamic -L"$bt" -ldl_bio -Wl,-rpath,"$bt"
for domain in graphics media audio; do
    hal="b/bridge/hals/$domain/libapklayer-hal-$domain.so"
    [ ! -e "$hal" ] || cp "$hal" "$native/"
done  # the host HAL library btload loads for the Android-side HAL services
# the LD_PRELOAD library (first in symbol lookup for every library of the process, first static TLS module): the path layer and bionic's TLS slots
cc -shared -fPIC -O2 -Wall -o "$native/libapklayer-preload.so" bridge/native/paths.c bridge/native/paths_preload.c bridge/native/bionic_tls.c -ldl
cc -O2 -Wall -o "$native/bin/aprop" bridge/native/aprop.c bridge/native/properties.c
install -m755 bridge/native/getprop "$native/bin/getprop"
java -cp "$classes:$(ls "$native"/aosp/*.jar | tr '\n' ':')" apklayer.host.CriticalNatives "$tmp/critical-natives.txt" $(ls "$shards" | grep -E "^framework\.jar[0-9]+$" | sed "s|^|$shards/|")
# apklayer patch: android.content.res is not in the javac shards, so its @CriticalNative methods (XmlBlock...) are listed from source
# (generated by scripts/gen-critical-from-source.py from the tree's android/content/res/*.java; native resources need them)
cat bridge/native/critical-natives-extra.txt >> "$tmp/critical-natives.txt"
# Our own versions of device libraries that need a service the desktop does not have (bridge/ndk/<name>.c): the source's
# functions plus weak do-nothing stubs for every other export of the real library, mapped by bionic_translation's cfg.d.
cfg="$native/share/bionic_translation/cfg.d/bionic_translation.cfg"
map_lib() { # map_lib <name Android code asks for> <file that answers>: replaces any earlier mapping of the name
    sed -i "/^$1[[:space:]]/d" "$cfg"
    echo "$1 $2" >> "$cfg"
}
ndk_lib() { # ndk_lib <real library name> <our file name>
    base="${1%.so}"
    nm -D --defined-only "$libs/$1" | awk '$2 ~ /[TW]/ {sub(/@.*/, "", $3); print "__attribute__((weak)) long " $3 "(void) { return 0; }"}' | sort -u > "$tmp/$base-stubs.c"
    cc -shared -fPIC -O2 -Wall -o "$native/$2" "bridge/ndk/$base.c" "$tmp/$base-stubs.c"
    map_lib "$1" "$2"
}
# apklayer patch: original SurfaceTexture consumers live in libnativedisplay.
# SurfaceFlinger now supplies its real Choreographer/display services as well.
[ -f "$libs/libnativedisplay.so" ]
sed -i '/^libnativedisplay.so[[:space:]]/d' "$cfg"
cc -shared -fPIC -O2 -Wall -o "$native/libcamera2ndk.so" bridge/ndk/libcamera2ndk.c  # no camera HAL: the camera NDK reports errors (Godot links it)
ndk_lib libselinux.so libapklayer_selinux.so  # still needed by the libraries that link it (the service manager no longer uses it)
mkdir -p "$tmp/jar/native/linux/x86_64" "$tmp/jar/native/linux/aarch64" && cp "$tmp/libandroid_runtime.so" "$tmp/jar/native/linux/x86_64/" && cp "$tmp/libandroid_runtime.so" "$tmp/jar/native/linux/aarch64/" && cp "$tmp/critical-natives.txt" "$tmp/jar/"
# apklayer patch (docs/PATCHES.md): Robolectric's loader refuses Linux aarch64; the patched class comes first in the jar
scripts/build-runtime-overlay.sh "$native" "$tmp/jar"
# Robolectric loads the library from the framework jar's own native/ first: keep the same copy there
(cd "$tmp/jar" && for j in "$native"/aosp/android-all/*.jar "$native"/android-all/*.jar; do zip -q "$j" native/linux/x86_64/libandroid_runtime.so native/linux/aarch64/libandroid_runtime.so; done)
# the patched bionic_translation libraries (property functions removed, SO_MAX, path hook): a stale copy in $native made the JVM spin in the property reader
for f in "$bt"/lib*_bio.so*; do [ -f "$f" ] && cp -f "$f" "$native/"; done
rm -rf "$tmp"
# our EGL (a bionic library built in the tree, aosp/hals/graphics/egl) answers for Android's libEGL once it is in the library set
[ ! -e "$libs/libapklayer_egl.so" ] || map_lib libEGL.so libapklayer_egl.so
# Android's GLES trampolines (libGLESv1_CM, libGLESv2 ...) dispatch through a hook table that Android's own libEGL stores in a thread-pointer
# slot; with our libEGL nothing fills it, so every GLES library is the host's (glvnd) instead
map_lib libGLESv1_CM.so libGLESv1_CM.so.1


# apklayer patch: preserve the optional original Android Vulkan loader frontend.
if [ -f "$libs/libapklayer_vulkan.so" ] && [ -f "$libs/vulkan.apklayer.so" ]; then
    map_lib libvulkan.so libapklayer_vulkan.so
fi

# apklayer patch: use the staged original OpenSL ES engine instead of the legacy host mapping.
[ ! -f "$libs/libOpenSLES.so" ] || sed -i '/^libOpenSLES.so[[:space:]]/d' "$cfg"
