#!/usr/bin/env python3
"""android-stubs: finds the symbols Android's native libraries need that nothing provides, and writes stubs for them.

For a directory of Android (bionic) shared libraries (the closure of libandroid_runtime.so copied from an AOSP build)
this lists every undefined, non-weak symbol that no library of the set, no bionic_translation library, no glibc library
and no hand-written platform shim defines, then writes a C file with a do-nothing function per symbol. Intended for
entry points the JVM-hosted runtime never calls (the Java OpenGL bindings, EGL internals); anything that is called
must be implemented properly in bridge/native/android_platform.c instead (PLAN P7).

Usage: android-stubs.py LIBDIR BT_BUILD_DIR PLATFORM_SO OUT.c [SYSTEM_MAPPED_SO ...]
  LIBDIR           the Android libraries (*.so)
  BT_BUILD_DIR     bionic_translation's build dir (lib*_bio.so.0; "bionic_<name>" counts as <name>)
  PLATFORM_SO      the compiled bridge/native/android_platform.c
  SYSTEM_MAPPED_SO desktop libraries that stand in for Android ones (e.g. libEGL.so.1); the Android libraries of the
                   same names (libEGL.so, libGLESv2.so, ...) are then not counted as providers
"""
import glob, os, subprocess, sys

libdir, btdir, platform, out = sys.argv[1:5]
system = sys.argv[5:]
REPLACED = {"libEGL.so", "libGLESv1_CM.so", "libGLESv2.so", "libGLESv3.so", "libvulkan.so"}


def symbols(path):
    for line in subprocess.run(["readelf", "-W", "--dyn-syms", path], capture_output=True, text=True).stdout.splitlines()[3:]:
        p = line.split()
        if len(p) >= 8:
            yield p[7].split("@")[0], p[6], p[4]


defined, undefined = set(), {}
for lib in glob.glob(os.path.join(libdir, "*.so")):
    name = os.path.basename(lib)
    for sym, ndx, bind in symbols(lib):
        if ndx == "UND":
            if bind != "WEAK":
                undefined.setdefault(sym, set()).add(name)
        elif name not in REPLACED:
            defined.add(sym)
for lib in glob.glob(os.path.join(btdir, "lib*_bio.so.0")) + [platform, "/lib/aarch64-linux-gnu/libc.so.6", "/lib/aarch64-linux-gnu/libm.so.6",
                                                              "/lib/aarch64-linux-gnu/libgcc_s.so.1"] + system:
    if os.path.exists(lib):
        for sym, ndx, bind in symbols(lib):
            if ndx != "UND":
                defined.add(sym)
                if sym.startswith("bionic_"):
                    defined.add(sym[len("bionic_"):])
missing = sorted(s for s in undefined if s not in defined)
with open(out, "w") as f:
    f.write("/* generated by scripts/android-stubs.py: do-nothing definitions of symbols Android's libraries import and\n"
            " * nothing provides (%d). Do not edit; regenerate. */\n" % len(missing))
    gl = [s for s in missing if s.startswith("gl")]
    for s in missing:
        if s in gl:  # GL extension entry points go to the host driver (a do-nothing stub made glEGLImageTargetTexture2DOES a no-op)
            f.write('__attribute__((used, visibility("hidden"))) void *stubslot_%s;\n' % s)
            f.write('#if defined(__aarch64__)\n'
                    '__asm__(".text\\n.globl %s\\n.type %s,%%function\\n%s:\\n\\tadrp x16, stubslot_%s\\n'
                    '\\tldr x16, [x16, :lo12:stubslot_%s]\\n\\tcbz x16, 1f\\n\\tbr x16\\n1:\\tmov x0, #0\\n\\tret\\n");\n' % ((s,) * 5))
            f.write('#elif defined(__x86_64__)\n'
                    '__asm__(".text\\n.globl %s\\n.type %s,@function\\n%s:\\n\\tmovq stubslot_%s(%%rip), %%r11\\n'
                    '\\ttestq %%r11, %%r11\\n\\tjz 1f\\n\\tjmp *%%r11\\n1:\\txorl %%eax, %%eax\\n\\tret\\n");\n#endif\n' % ((s,) * 4))
        else:
            f.write("long %s(void) { return 0; }\n" % s)
    f.write("#include <dlfcn.h>\nstatic void __attribute__((constructor)) resolve_gl_stubs(void) {\n"
            "    void *egl = dlopen(\"libEGL.so.1\", RTLD_LAZY | RTLD_GLOBAL);\n"
            "    void *(*gpa)(const char *) = egl ? dlsym(egl, \"eglGetProcAddress\") : 0;\n    if (!gpa) return;\n")
    for s in gl:
        f.write('    extern void *stubslot_%s; stubslot_%s = gpa("%s");\n' % (s, s, s))
    f.write("}\n")
print(len(missing), "stubs ->", out)
