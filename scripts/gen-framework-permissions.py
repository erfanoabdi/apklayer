#!/usr/bin/env python3
"""The framework's permission definitions (name, base protection level) from the tree's core/res/AndroidManifest.xml, for the instance hub's permission checks:
runtime/host/resources/framework-permissions.txt (committed). Usage: scripts/gen-framework-permissions.py [path-to-AndroidManifest.xml]"""
import pathlib, sys
import xml.etree.ElementTree as ET

ns = '{http://schemas.android.com/apk/res/android}'
src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '/Users/erfanabdi/OrbStack/ubuntu22-x86/home/erfanabdi/los24/frameworks/base/core/res/AndroidManifest.xml')
rows = []
for el in ET.parse(src).getroot().iter('permission'):
    name, level = el.get(ns + 'name'), el.get(ns + 'protectionLevel', 'normal')
    if name: rows.append('%s %s' % (name, level.split('|')[0].strip()))
out = pathlib.Path(__file__).resolve().parent.parent / 'runtime/host/resources/framework-permissions.txt'
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('# generated by scripts/gen-framework-permissions.py from the tree\'s frameworks/base/core/res/AndroidManifest.xml: <permission> <base protection level>\n' + '\n'.join(sorted(rows)) + '\n')
print(len(rows), 'permissions ->', out)
