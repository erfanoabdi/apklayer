#!/usr/bin/env python3
"""astc-real.h: real ASTC blocks (astcenc's encode of a noisy test picture, (bx+1)x(by+1) texels: four blocks, partial edge blocks) and what astcenc itself
decodes them to, for every block size, LDR and sRGB profile. Usage (needs astcenc, python3-pil, python3-numpy): python3 gen-astc.py > astc-real.h"""
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image

DIMS = [(4, 4), (5, 4), (5, 5), (6, 5), (6, 6), (8, 5), (8, 6), (8, 8), (10, 5), (10, 6), (10, 8), (10, 10), (12, 10), (12, 12)]


def picture(w, h, seed):
    rng = np.random.default_rng(seed)
    y, x = np.mgrid[0:h, 0:w]
    img = np.zeros((h, w, 4), np.float32)
    img[..., 0] = x / max(w - 1, 1)
    img[..., 1] = y / max(h - 1, 1)
    img[..., 2] = 0.5 + 0.5 * np.sin((x + y) / 3.0 + seed)
    img[..., 3] = 1 - 0.7 * x / max(w - 1, 1)
    img[:, w // 2:, :3] = 1 - img[:, w // 2:, :3]
    img[h // 2:, : w // 2] = rng.random((h - h // 2, w // 2, 4))
    return Image.fromarray((img * 255).astype(np.uint8), 'RGBA')


def arr(name, data):
    return 'static const unsigned char %s[] = {%s};' % (name, ','.join(str(b) for b in data))


work = Path(tempfile.mkdtemp(prefix='astc-real-'))
print('/* generated by gen-astc.py (astcenc %s): real ASTC blocks and their reference decode (RGBA8, top row first) */' % subprocess.run(['astcenc', '-version'], capture_output=True, text=True).stdout.split()[1])
table = []
for srgb in (0, 1):
    for i, (bx, by) in enumerate(DIMS):
        w, h = bx + 1, by + 1
        png, astc, ref = work / 'a.png', work / 'a.astc', work / 'a.ref.png'
        picture(w, h, i + 1).save(png)
        subprocess.run(['astcenc', '-cs' if srgb else '-cl', str(png), str(astc), '%dx%d' % (bx, by), '-medium'], check=True, capture_output=True)
        subprocess.run(['astcenc', '-ds' if srgb else '-dl', str(astc), str(ref)], check=True, capture_output=True)
        name = 'astc_%s%dx%d' % ('s' if srgb else 'l', bx, by)
        print(arr(name + '_blocks', astc.read_bytes()[16:]))
        print(arr(name + '_rgba', np.array(Image.open(ref).convert('RGBA')).tobytes()))
        table.append('    { %d, %d, %d, %d, %s_blocks, sizeof %s_blocks, %s_rgba },' % (srgb, i, w, h, name, name, name))
print('static const struct { int srgb, index, w, h; const unsigned char *blocks; int bytes; const unsigned char *rgba; } astc_real[] = {')
print('\n'.join(table))
print('};')
