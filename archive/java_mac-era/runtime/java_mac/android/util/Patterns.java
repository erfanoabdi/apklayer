            "\uDB44\uDC00-\uDB7F\uDFFD" +
            "&&[^\u00A0[\u2000-\u200A]\u2028\u2029\u202F\u3000]]";
    private static final String LABEL_CHAR = "a-zA-Z0-9" + UCS_CHAR;
    private static final String TLD_CHAR   = "a-zA-Z" + UCS_CHAR;
    private static final String IRI_LABEL =
            "[" + LABEL_CHAR + "](?:[" + LABEL_CHAR + "_\\-]{0,61}[" + LABEL_CHAR + "]){0,1}";
    private static final String PUNYCODE_TLD = "xn\\-\\-[\\w\\-]{0,58}\\w";
    private static final String TLD = "(" + PUNYCODE_TLD + "|" + "[" + TLD_CHAR + "]{2,63}" + ")";
    private static final String HOST_NAME = "(" + IRI_LABEL + "\\.)+" + TLD;
    private static final String IP_ADDRESS_STRING =
            "((25[0-5]|2[0-4][0-9]|[0-1][0-9]{2}|[1-9][0-9]|[1-9])\\.(25[0-5]|2[0-4]"
            + "[0-9]|[0-1][0-9]{2}|[1-9][0-9]|[1-9]|0)\\.(25[0-5]|2[0-4][0-9]|[0-1]"
            + "[0-9]{2}|[1-9][0-9]|[1-9]|0)\\.(25[0-5]|2[0-4][0-9]|[0-1][0-9]{2}"
            + "|[1-9][0-9]|[0-9]))";
    /** AOSP: matches a host name or a dotted-quad IPv4 literal. */
    public static final Pattern DOMAIN_NAME =
            Pattern.compile("(" + HOST_NAME + "|" + IP_ADDRESS_STRING + ")");
    /** AOSP Patterns.IP_ADDRESS. */
    public static final Pattern IP_ADDRESS = Pattern.compile(IP_ADDRESS_STRING);

    public static final Pattern WEB_URL = Pattern.compile(
        "(?:(?:https?|ftp)://|www\\.)"
        + "[a-zA-Z0-9\\-._~%]+(?:\\.[a-zA-Z0-9\\-._~%]+)+"
        + "(?::\\d{1,5})?"
        + "(?:[/?#][^\\s<>\"]*)?",
        Pattern.CASE_INSENSITIVE);

    /** Matches a domain.tld[/path] even without a scheme (AOSP AUTOLINK_WEB_URL
     *  is broader; this covers the same auto-link cases for descriptions). */
    public static final Pattern AUTOLINK_WEB_URL = WEB_URL;

