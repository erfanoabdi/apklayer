    /**
     * Concatenate every non-null capture group of {@code matcher}, in order.
     * AOSP: Patterns.concatGroups(Matcher). Group 0 (the whole match) is
     * deliberately excluded -- the loop starts at 1.
     */
    public static final String concatGroups(java.util.regex.Matcher matcher) {
        StringBuilder b = new StringBuilder();
        final int numGroups = matcher.groupCount();

        for (int i = 1; i <= numGroups; i++) {
            String s = matcher.group(i);

            if (s != null) {
                b.append(s);
            }
        }

        return b.toString();
    }

    /**
     * Strip everything except digits and '+' out of the current match.
     * AOSP: Patterns.digitsAndPlusOnly(Matcher). Note AOSP keeps EVERY '+',
     * not just a leading one -- transcribed as written rather than "fixed",
     * because Linkify's tel: URI construction is calibrated to this output.
     */
    public static final String digitsAndPlusOnly(java.util.regex.Matcher matcher) {
        StringBuilder buffer = new StringBuilder();
        String matchingRegion = matcher.group();

        for (int i = 0, size = matchingRegion.length(); i < size; i++) {
            char character = matchingRegion.charAt(i);

            if (character == '+' || Character.isDigit(character)) {
                buffer.append(character);
            }
        }
        return buffer.toString();
    }
