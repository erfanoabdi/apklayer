/* FSR 1 (AMD FidelityFX Super Resolution 1, MIT, ffx_fsr1.h) as GLES2 fragment shaders: FS_UP (EASU) and FS_CAS (RCAS plus the optional text aid). sharpen.c includes it; tools/gen/sharpen-spv.py turns it into sharpen_vk_spv.h.
 * EASU and RCAS follow the reference line by line (same constants, same 12 taps, same min/max clamps); what differs is listed in docs/THIRD_PARTY.md: the gather4 loads are
 * twelve texel-centre fetches (the same texels), the approximate rcp/rsq are exact divisions, the zero-division guards RCAS needs without the reference's rcp(0)=inf, and the text aid (not AMD's). The picture is
 * used as it is stored: the apps' buffers are gamma encoded, which is the perceptual space the reference asks for (no transfer function: FsrRcasInput is the identity).
 * A source larger than the output (render scale above 100) is averaged down instead. */
static const char *FS_UP =
    "#extension GL_OES_EGL_image_external : require\n"
    "precision highp float;\n"
    "uniform samplerExternalOES tex; uniform vec2 src; uniform float down; varying vec2 uv;\n"
    "vec3 T(vec2 q) { return texture2D(tex, (q + 0.5) / src).rgb; }\n"  /* the gather4 of the reference: the texel (q) itself, fetched at its centre */
    "float L(vec3 c) { vec3 q = floor(c * 255.0 + 0.5); return q.b * (0.5 / 255.0) + (q.r * (0.5 / 255.0) + q.g * (1.0 / 255.0)); }  /* apklayer patch: the luma on the 8 bit lattice, which is what the reference's gather of 8 bit texels sees: the sampler's unorm conversion is off by ~1e-4 (NVIDIA), and equal lumas from other colours would turn into a direction / length tie break (up to 12 levels wrong at 0.03% of the pixels) */\n"
    "void setf(inout vec2 dir, inout float len, float w, float lA, float lB, float lC, float lD, float lE) {\n"
    "  float dc = lD - lC, cb = lC - lB;\n"
    "  float lenX = 1.0 / max(max(abs(dc), abs(cb)), 1e-6), dirX = lD - lB;\n"
    "  dir.x += dirX * w;\n"
    "  lenX = clamp(abs(dirX) * lenX, 0.0, 1.0); lenX *= lenX; len += lenX * w;\n"
    "  float ec = lE - lC, ca = lC - lA;\n"
    "  float lenY = 1.0 / max(max(abs(ec), abs(ca)), 1e-6), dirY = lE - lA;\n"
    "  dir.y += dirY * w;\n"
    "  lenY = clamp(abs(dirY) * lenY, 0.0, 1.0); lenY *= lenY; len += lenY * w;\n"
    "}\n"
    "void tap(inout vec3 aC, inout float aW, vec2 off, vec2 dir, vec2 len, float lob, float clp, vec3 c) {\n"
    "  vec2 v = vec2(off.x * dir.x + off.y * dir.y, off.x * -dir.y + off.y * dir.x) * len;\n"
    "  float d2 = min(v.x * v.x + v.y * v.y, clp);\n"
    "  float wB = 2.0 / 5.0 * d2 - 1.0, wA = lob * d2 - 1.0;\n"
    "  wB *= wB; wA *= wA;\n"
    "  wB = 25.0 / 16.0 * wB - (25.0 / 16.0 - 1.0);\n"
    "  float w = wB * wA;\n"
    "  aC += c * w; aW += w;\n"
    "}\n"
    "void main() {\n"
    "  if (down > 0.5) {  /* a larger source than the output: the four taps around the pixel average it */\n"
    "    vec2 h = 0.5 / src * down;\n"
    "    vec3 r = 0.25 * (texture2D(tex, uv + vec2(-h.x, -h.y)).rgb + texture2D(tex, uv + vec2(h.x, -h.y)).rgb + texture2D(tex, uv + vec2(-h.x, h.y)).rgb + texture2D(tex, uv + vec2(h.x, h.y)).rgb);\n"
    "    gl_FragColor = vec4(r, 1.0); return;\n"
    "  }\n"
    "  vec2 pp = uv * src - 0.5, fp = floor(pp);  /* f's texel; the pixel centre maps to (ip + 0.5) * scale - 0.5 as in FsrEasuCon */\n"
    "  pp -= fp;\n"
    "  /*   b c        f g j k are the four texels round the sample\n"
    "     e f g h\n"
    "     i j k l\n"
    "       n o   */\n"
    "  vec3 b = T(fp + vec2(0.0, -1.0)), c = T(fp + vec2(1.0, -1.0)), e = T(fp + vec2(-1.0, 0.0)), f = T(fp), g = T(fp + vec2(1.0, 0.0)), h = T(fp + vec2(2.0, 0.0));\n"
    "  vec3 i = T(fp + vec2(-1.0, 1.0)), j = T(fp + vec2(0.0, 1.0)), k = T(fp + vec2(1.0, 1.0)), l = T(fp + vec2(2.0, 1.0)), n = T(fp + vec2(0.0, 2.0)), o = T(fp + vec2(1.0, 2.0));\n"
    "  float bL = L(b), cL = L(c), eL = L(e), fL = L(f), gL = L(g), hL = L(h), iL = L(i), jL = L(j), kL = L(k), lL = L(l), nL = L(n), oL = L(o);\n"
    "  vec2 dir = vec2(0.0); float len = 0.0;\n"
    "  setf(dir, len, (1.0 - pp.x) * (1.0 - pp.y), bL, eL, fL, gL, jL);\n"
    "  setf(dir, len, pp.x * (1.0 - pp.y), cL, fL, gL, hL, kL);\n"
    "  setf(dir, len, (1.0 - pp.x) * pp.y, fL, iL, jL, kL, nL);\n"
    "  setf(dir, len, pp.x * pp.y, gL, jL, kL, lL, oL);\n"
    "  vec2 dir2 = dir * dir;\n"
    "  float dirR = dir2.x + dir2.y;\n"
    "  bool zro = dirR < (1.0 / 32768.0);\n"
    "  dirR = zro ? 1.0 : inversesqrt(dirR);\n"
    "  dir.x = zro ? 1.0 : dir.x;\n"
    "  dir *= dirR;\n"
    "  len = len * 0.5; len *= len;\n"
    "  float stretch = (dir.x * dir.x + dir.y * dir.y) / max(abs(dir.x), abs(dir.y));\n"
    "  vec2 len2 = vec2(1.0 + (stretch - 1.0) * len, 1.0 + -0.5 * len);\n"
    "  float lob = 0.5 + ((1.0 / 4.0 - 0.04) - 0.5) * len, clp = 1.0 / lob;\n"
    "  vec3 min4 = min(min(f, g), min(j, k)), max4 = max(max(f, g), max(j, k));\n"
    "  vec3 aC = vec3(0.0); float aW = 0.0;\n"
    "  tap(aC, aW, vec2(0.0, -1.0) - pp, dir, len2, lob, clp, b);\n"
    "  tap(aC, aW, vec2(1.0, -1.0) - pp, dir, len2, lob, clp, c);\n"
    "  tap(aC, aW, vec2(-1.0, 1.0) - pp, dir, len2, lob, clp, i);\n"
    "  tap(aC, aW, vec2(0.0, 1.0) - pp, dir, len2, lob, clp, j);\n"
    "  tap(aC, aW, vec2(0.0, 0.0) - pp, dir, len2, lob, clp, f);\n"
    "  tap(aC, aW, vec2(-1.0, 0.0) - pp, dir, len2, lob, clp, e);\n"
    "  tap(aC, aW, vec2(1.0, 1.0) - pp, dir, len2, lob, clp, k);\n"
    "  tap(aC, aW, vec2(2.0, 1.0) - pp, dir, len2, lob, clp, l);\n"
    "  tap(aC, aW, vec2(2.0, 0.0) - pp, dir, len2, lob, clp, h);\n"
    "  tap(aC, aW, vec2(1.0, 0.0) - pp, dir, len2, lob, clp, g);\n"
    "  tap(aC, aW, vec2(1.0, 2.0) - pp, dir, len2, lob, clp, o);\n"
    "  tap(aC, aW, vec2(0.0, 2.0) - pp, dir, len2, lob, clp, n);\n"
    "  gl_FragColor = vec4(min(max4, max(min4, aC * (1.0 / aW))), 1.0);  /* normalise and dering */\n"
    "}\n";

/* RCAS (reference FsrRcasF; FSR_RCAS_LIMIT 0.25 - 1/16, no denoise as in the reference's default): sharpening from the 5-tap cross, the strength per pixel limited so the result stays inside the range (no clipping, no halos).
 * `sharp` is the reference's constant from FsrRcasCon, exp2(-stops): 1 the sharpest (0 stops), 0.87 the reference default (0.2 stops), 0.5 one stop less, 0 off (the picture passes unchanged).
 * The text aid (`text` 1, not AMD's): where the 3x3 around the pixel is strong two-colour structure with a mostly axis-aligned gradient (a glyph stem, an icon edge, a UI line), the pixel gets an extra unsharp
 * step along that axis, clamped to the 3x3's per-channel min/max (so it cannot overshoot); elsewhere (3D, photos, gradients) the result is the plain RCAS. */
static const char *FS_CAS =
    "precision highp float;\n"
    "uniform sampler2D tex; uniform vec2 px; uniform float sharp; uniform float text; varying vec2 uv;\n"
    "const float TEXTK = 2.0;\n"
    "const bool DENOISE = false;  /* FSR_RCAS_DENOISE of the reference: off by default there too */\n"
    "vec3 T(float x, float y) { return texture2D(tex, uv + vec2(x, y) * px).rgb; }\n"
    "float L(vec3 c) { return c.b * 0.5 + (c.r * 0.5 + c.g); }\n"
    "void main() {\n"
    "  vec3 b = T(0.0, -1.0), d = T(-1.0, 0.0), e = T(0.0, 0.0), f = T(1.0, 0.0), h = T(0.0, 1.0);\n"
    "  float bL = L(b), dL = L(d), eL = L(e), fL = L(f), hL = L(h);\n"
    "  vec3 mn4 = min(min(b, d), min(f, h)), mx4 = max(max(b, d), max(f, h));\n"
    "  vec3 hitMin = min(mn4, e) / max(4.0 * mx4, 1e-5);  /* (the reference divides by 4 * mx4 and relies on the GPU's max() ignoring the NaN of 0/0) */\n"
    "  vec3 hitMax = (1.0 - max(mx4, e)) / min(4.0 * mn4 - 4.0, -1e-5);\n"
    "  vec3 lobeV = max(-hitMin, hitMax);\n"
    "  float lobe = max(-(0.25 - 1.0 / 16.0), min(max(lobeV.r, max(lobeV.g, lobeV.b)), 0.0)) * sharp;\n"
    "  if (DENOISE) {\n"
    "    float nz = 0.25 * bL + 0.25 * dL + 0.25 * fL + 0.25 * hL - eL;\n"
    "    nz = clamp(abs(nz) / max(max(max(max(bL, dL), max(eL, fL)), hL) - min(min(min(bL, dL), min(eL, fL)), hL), 1e-5), 0.0, 1.0);\n"
    "    lobe *= -0.5 * nz + 1.0;\n"
    "  }\n"
    "  float keep = 1.0;  /* alpha: 1 - the text mask, for the anti-aliasing pass that may follow (sharpen_post.h: it leaves text pixels alone); the output buffers are X formats, alpha is ignored there */\n"
    "  vec3 pix = (lobe * b + lobe * d + lobe * h + lobe * f + e) / (4.0 * lobe + 1.0);\n"
    "  if (text > 0.5) {\n"
    "    vec3 a = T(-1.0, -1.0), c = T(1.0, -1.0), g = T(-1.0, 1.0), i = T(1.0, 1.0);\n"
    "    float aL = L(a), cL = L(c), gL = L(g), iL = L(i);\n"
    "    vec3 mn = min(min(min(a, c), min(g, i)), mn4), mx = max(max(max(a, c), max(g, i)), mx4);\n"
    "    mn = min(mn, e); mx = max(mx, e);\n"
    "    float ctr = 0.5 * (max(max(max(aL, cL), max(gL, iL)), max(max(max(bL, dL), max(eL, fL)), hL)) - min(min(min(aL, cL), min(gL, iL)), min(min(min(bL, dL), min(eL, fL)), hL)));\n"
    "    /* two colours only: every pixel of the 3x3 lies near the line between the darkest and the brightest one */\n"
    "    vec3 cLo = a, cHi = a; float lLo = aL, lHi = aL;\n"
    "    if (bL < lLo) { lLo = bL; cLo = b; } if (bL > lHi) { lHi = bL; cHi = b; }\n"
    "    if (cL < lLo) { lLo = cL; cLo = c; } if (cL > lHi) { lHi = cL; cHi = c; }\n"
    "    if (dL < lLo) { lLo = dL; cLo = d; } if (dL > lHi) { lHi = dL; cHi = d; }\n"
    "    if (eL < lLo) { lLo = eL; cLo = e; } if (eL > lHi) { lHi = eL; cHi = e; }\n"
    "    if (fL < lLo) { lLo = fL; cLo = f; } if (fL > lHi) { lHi = fL; cHi = f; }\n"
    "    if (gL < lLo) { lLo = gL; cLo = g; } if (gL > lHi) { lHi = gL; cHi = g; }\n"
    "    if (hL < lLo) { lLo = hL; cLo = h; } if (hL > lHi) { lHi = hL; cHi = h; }\n"
    "    if (iL < lLo) { lLo = iL; cLo = i; } if (iL > lHi) { lHi = iL; cHi = i; }\n"
    "    vec3 ax = cHi - cLo; float axx = max(dot(ax, ax), 1e-6), res = 0.0;\n"
    "    vec3 q[9]; q[0] = a; q[1] = b; q[2] = c; q[3] = d; q[4] = e; q[5] = f; q[6] = g; q[7] = h; q[8] = i;\n"
    "    for (int k = 0; k < 9; k++) res = max(res, length(q[k] - cLo - ax * clamp(dot(q[k] - cLo, ax) / axx, 0.0, 1.0)));\n"
    "    /* a mostly horizontal or vertical gradient (Sobel) */\n"
    "    float gx = (cL + 2.0 * fL + iL) - (aL + 2.0 * dL + gL), gy = (gL + 2.0 * hL + iL) - (aL + 2.0 * bL + cL);\n"
    "    float axis = abs(abs(gx) - abs(gy)) / (abs(gx) + abs(gy) + 1e-4);\n"
    "    float t = smoothstep(0.28, 0.5, ctr) * (1.0 - smoothstep(0.04, 0.10, res)) * smoothstep(0.3, 0.65, axis);\n"
    "    bool hx = abs(gx) > abs(gy);  /* the axis the gradient runs along */\n"
    "    vec3 p1 = hx ? d : b, q1 = hx ? f : h, p2 = hx ? T(-2.0, 0.0) : T(0.0, -2.0), q2 = hx ? T(2.0, 0.0) : T(0.0, 2.0);\n"
    "    mn = min(mn, min(p2, q2)); mx = max(mx, max(p2, q2));\n"
    "    vec3 lap = e - 0.25 * (p1 + q1 + 0.5 * (p2 + q2)) * (4.0 / 3.0);\n"
    "    pix = mix(pix, clamp(pix + TEXTK * lap, mn, mx), t);\n"
    "    keep = 1.0 - t;\n"
    "  }\n"
    "  gl_FragColor = vec4(clamp(pix, 0.0, 1.0), keep);\n"
    "}\n";
