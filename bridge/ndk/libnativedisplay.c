/* libnativedisplay for the arm64 native runtime (PLAN P7). The device library gets vsync from SurfaceFlinger over binder
 * (ComposerService); there is none here. Choreographer instead follows the real display: apklayer's shell turns
 * wl_surface.frame callbacks into vsync messages, the host JVM (HostVsync.java) relays them on the socket
 * $XDG_RUNTIME_DIR/apklayer/vsync-<pid>.sock together with the output's refresh rate (wl_output.mode). Nothing is
 * invented: without a shell there is no vsync. HWUI's RenderThread polls getFd() and calls handlePendingEvents().
 * Every other export of the real library (ASurfaceTexture, ADisplay, ...) is a weak do-nothing stub generated by
 * scripts/build-native-arm64.sh. Loaded through bionic_translation's cfg.d (libnativedisplay.so). */
#define _GNU_SOURCE
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <sys/socket.h>
#include <sys/un.h>
#include <time.h>
#include <unistd.h>

typedef void (*vsync_cb)(const void *data, void *user);
struct frame_data { int64_t frame_time_ns, interval_ns; };
struct choreographer { int fd; vsync_cb cb; void *user; int requested; struct frame_data data; };

static int64_t now_ns(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (int64_t)ts.tv_sec * 1000000000 + ts.tv_nsec;
}

void *AChoreographer_create(void)
{
    struct choreographer *c = calloc(1, sizeof *c);
    c->data.interval_ns = 16666667; /* until the shell reports the output's refresh rate */
    c->fd = socket(AF_UNIX, SOCK_STREAM | SOCK_CLOEXEC | SOCK_NONBLOCK, 0);
    struct sockaddr_un a = { .sun_family = AF_UNIX };
    const char *rt = getenv("XDG_RUNTIME_DIR");
    snprintf(a.sun_path, sizeof a.sun_path, "%s/apklayer/vsync-%d.sock", rt ? rt : "/tmp", (int)getpid());
    if (connect(c->fd, (struct sockaddr *)&a, sizeof a) < 0) {
        fprintf(stderr, "[nativedisplay] no vsync source (%s): Choreographer callbacks will not fire\n", a.sun_path);
        close(c->fd);
        c->fd = socket(AF_UNIX, SOCK_STREAM | SOCK_CLOEXEC | SOCK_NONBLOCK, 0); /* a quiet fd for the poller */
    }
    return c;
}

void AChoreographer_destroy(struct choreographer *c) { close(c->fd); free(c); }
int AChoreographer_getFd(struct choreographer *c) { return c->fd; }

void AChoreographer_postVsyncCallback(struct choreographer *c, vsync_cb cb, void *user)
{
    c->cb = cb;
    c->user = user;
    if (c->requested) return;
    c->requested = 1;
    uint32_t request = 1;
    if (write(c->fd, &request, sizeof request) < 0) c->requested = 0;
}

void AChoreographer_handlePendingEvents(struct choreographer *c, void *data)
{
    (void)data;
    uint32_t rec[2];
    while (read(c->fd, rec, sizeof rec) == sizeof rec) {
        if (rec[0] == 1 && rec[1]) c->data.interval_ns = 1000000000000LL / rec[1]; /* mHz */
        if (rec[0] != 2) continue;
        /* the compositor's callback time is a 32 bit ms count of the same monotonic clock: widen it to ns */
        int64_t now = now_ns(), ms = now / 1000000;
        c->data.frame_time_ns = now - ((ms - (int64_t)rec[1]) & 0xffffffffLL) * 1000000;
        c->requested = 0;
        vsync_cb cb = c->cb;
        c->cb = NULL;
        if (cb) cb(&c->data, c->user);
    }
}

void AChoreographer_registerRefreshRateCallback(void *c, void *cb, void *user) { (void)c; (void)cb; (void)user; }
int64_t _ZN7android31AChoreographer_getFrameIntervalEPK14AChoreographer(const struct choreographer *c) { return c->data.interval_ns; }

int64_t AChoreographerFrameCallbackData_getFrameTimeNanos(const struct frame_data *d) { return d->frame_time_ns; }
size_t AChoreographerFrameCallbackData_getFrameTimelinesLength(const void *d) { (void)d; return 1; }
size_t AChoreographerFrameCallbackData_getPreferredFrameTimelineIndex(const void *d) { (void)d; return 0; }
